create or replace function pg_temp.ptree(s text) returns table(node_id int, parent_id int, ord int, depth int, element text, role text)
language plpgsql as $f$
declare i int := 1; n int := length(s); j int; c text; tok text; rl text; cnt int := 0; d int; stack int[] := '{}'; ocs int[] := '{}';
begin
  while i <= n loop
    j := i;
    while j <= n and substr(s, j, 1) not in ('(', ')', ',', '*') loop j := j + 1; end loop;
    tok := substr(s, i, j - i); i := j; rl := null;
    if i <= n and substr(s, i, 1) = '*' then
      rl := case substr(s, i + 1, 1) when 'p' then 'phonetic' when 's' then 'semantic' end; i := i + 2;
    end if;
    cnt := cnt + 1; d := coalesce(array_length(stack, 1), 0) + 1;
    ocs[d] := coalesce(ocs[d], 0) + 1;
    node_id := cnt; parent_id := case when d = 1 then null else stack[d - 1] end; ord := ocs[d]; depth := d; element := tok; role := rl;
    return next;
    if i <= n and substr(s, i, 1) = '(' then
      stack := stack || cnt; ocs[d + 1] := 0; i := i + 1;
    else
      while i <= n and substr(s, i, 1) = ')' loop stack := stack[1:coalesce(array_length(stack, 1), 1) - 1]; i := i + 1; end loop;
      if i <= n and substr(s, i, 1) = ',' then i := i + 1; end if;
    end if;
  end loop;
end $f$;

